// Large-character fixtures (plugin 1.9.0): the deterministic stress rig of the core tests
// (`cutout-core-tests.exe --stress-rig`: 200 bones, 150 slots, 40 meshes, 30 clips, skins,
// expressions, IK, events) and exported games that place it many times on one screen.
import { spawnSync } from 'node:child_process';
import { cp, mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { extname, resolve } from 'node:path';
import { loadProject } from '../../dist/packages/project-service/loader.js';
import { buildSnapshot } from '../../dist/packages/project-service/snapshot.js';
import { NATIVE_APP, WEB_APP, png } from './player-extension-fixture.mjs';

export const CORE_TESTS = resolve('dist/cutout/build-win/cutout-core-tests.exe');
let cached;
/** {rig, controller, images}: generated by the native core test binary (same data everywhere). */
export function stressRig() {
  if (!cached) {
    const r = spawnSync(CORE_TESTS, ['--stress-rig'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
    if (r.status !== 0) throw new Error(`--stress-rig failed: ${r.stderr}`);
    cached = JSON.parse(r.stdout);
  }
  return structuredClone(cached);
}
/** A small solid PNG per image id (distinct colours), so every part draws real pixels. */
export function stressImage(id) {
  let h = 0;
  for (const ch of id) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return png(32, 32, [60 + h % 180, 60 + (h >> 8) % 180, 60 + (h >> 16) % 180]);
}
export const stressInstance = i => `home/stress-${i}`;
/**
 * Exported game (target 'windows' | 'web') with `instances` stress characters on the home screen
 * (a 5-column grid of 240×170 boxes). Built like player-extension-fixture's makeGame.
 */
export async function makeStressGame({ target, name, instances = 20 }) {
  const { rig, controller, images } = stressRig();
  await mkdir(resolve('.cache/anim-tests'), { recursive: true });
  const root = await mkdtemp(resolve(`.cache/anim-tests/${name}-`)), game = resolve(root, 'game');
  const built = await buildSnapshot(await loadProject(resolve('examples/academy-journey')));
  if (!built.ok) throw new Error(JSON.stringify(built.diagnostics));
  const content = structuredClone(built.snapshot);
  const home = content.project.visual.screens.find(s => s.id === 'home');
  for (let i = 0; i < instances; i++)
    home.elements.push({ id: `stress-${i}`, kind: 'plugin', x: 20 + (i % 5) * 245, y: 60 + Math.floor(i / 5) * 165, width: 240, height: 170,
      extension: { plugin: 'cutout-animation', type: 'character', ref: 'stress-main', props: { scale: 1, flipX: false } } });
  await cp(target === 'windows' ? NATIVE_APP : WEB_APP, game, { recursive: true });
  await mkdir(resolve(game, 'assets'), { recursive: true });
  const assets = {};
  for (const asset of content.assets) {
    const relative = `assets/${asset.id}${extname(asset.path).toLowerCase()}`;
    await cp(resolve('examples/academy-journey', asset.path), resolve(game, relative)); assets[asset.id] = relative;
  }
  for (const id of images) { await writeFile(resolve(game, `assets/${id}.png`), stressImage(id)); assets[id] = `assets/${id}.png`; }
  const module = target === 'windows' ? 'cutout-runtime.dll' : 'cutout-runtime.mjs';
  const extensions = { version: 1, plugins: [{ id: 'cutout-animation', version: '1.9.0', abi: 'raising-extension-1', entry: `plugins/cutout-animation/${module}`,
    documents: [{ type: 'rig', id: 'stress', data: rig }, { type: 'controller', id: 'stress-main', data: { ...controller, rig: 'stress' } }] }] };
  await mkdir(resolve(game, 'plugins/cutout-animation'), { recursive: true });
  for (const f of target === 'windows' ? ['build-win/cutout-runtime.dll'] : ['build-wasm/cutout-runtime.mjs', 'build-wasm/cutout-runtime.wasm'])
    await cp(resolve('dist/cutout', f), resolve(game, 'plugins/cutout-animation', f.split('/')[1]));
  await writeFile(resolve(game, 'game.json'), JSON.stringify({ formatVersion: '1', content, assets, extensions }));
  return { root, game, content };
}
