import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { openJourneyStudio, click, state } from '../journey/gui-helpers.mjs';

test('packaged Studio creates adventure sample and runs native equip, unequip and saved restoration', { timeout: 120000 }, async t => {
  assert.ok(process.env.STUDIO_EXECUTABLE, 'Use the packaged Studio executable');
  const { app, page, root, save, errors } = await openJourneyStudio(t);
  const output = resolve('output/playwright/commercial-systems-package'); await mkdir(output, { recursive: true });
  const host = await app.evaluate(({app})=>({packaged:app.isPackaged,exe:app.getPath('exe'),path:app.getAppPath()}));
  assert.equal(host.packaged,true);
  await click(page,'탐험·전투 샘플 새 프로젝트');
  await page.getByText(resolve(root),{exact:true}).waitFor();
  const project=JSON.parse(await readFile(resolve(root,'project.json'),'utf8'));
  assert.ok(project.systems.expeditions.some(e=>e.id==='forest'));
  await click(page,'플레이 미리보기'); await click(page,'새 게임 시작');
  assert.equal((await page.evaluate(()=>window.player.view())).view.runtimeBackend,'native');
  await click(page,'일정'); await click(page,'도시로 외출'); await click(page,'꽃집으로 이동');
  await click(page,'연습용 검 구매'); await click(page,'우리 집 방문'); await click(page,'모험 준비');
  await click(page,'장착 · 연습용 검');
  const equipped=await state(page); assert.equal(equipped.systems.equipment.weapon,'wooden-sword');
  const view=(await page.evaluate(()=>window.player.view())).view;
  assert.equal(view.systems.equipment.find(e=>e.id==='wooden-sword').canUnequip,true);
  await click(page,'저장'); await page.waitForFunction(()=>[...document.querySelectorAll('[role=status]')].some(e=>e.textContent.includes('게임을 저장')));
  await click(page,'장착 해제 · 연습용 검');
  assert.equal((await state(page)).systems.equipment.weapon,null);
  await click(page,'불러오기');
  assert.deepEqual(await state(page),equipped);
  assert.equal(await page.getByRole('button',{name:'장착 해제 · 연습용 검',exact:true}).isEnabled(),true);
  const native=await app.evaluate(()=>({resourcesPath:process.resourcesPath,loaded:Object.keys(process.getBuiltinModule('module')._cache).filter(file=>file.endsWith('.node'))}));
  const manifest=JSON.parse(await readFile(resolve(native.resourcesPath,'native/addon.json'),'utf8'));
  assert.ok(native.loaded.includes(resolve(native.resourcesPath,'native',manifest.filename)),JSON.stringify(native));
  await page.screenshot({path:resolve(output,'adventure-equipped.png')});
  assert.deepEqual(errors,[]);
  const evidence={host,project:root,save,native,manifest,equipment:equipped.systems.equipment,checks:['packaged adventure create','native addon loaded','GUI buy/equip/unequip','save/load exact state'],errors};
  await writeFile(resolve(output,'evidence.json'),JSON.stringify(evidence,null,2));
  console.log(JSON.stringify({project:root,executable:host.exe,addon:manifest.filename,evidence:resolve(output,'evidence.json')}));
});
